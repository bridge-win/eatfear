const { chromium } = require('playwright')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
;(async () => {
  await fs.mkdir('artifacts/cn', { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN', acceptDownloads: true })
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const base = process.env.CN_TEST_URL || 'http://localhost:3111'
  await page.goto(base + '/cn', { waitUntil: 'domcontentloaded', timeout: 60000 })
  await page.getByRole('heading', { level: 1 }).waitFor()
  await page.waitForTimeout(30000)
  const report = { testedAt: new Date().toISOString(), checks: [], runtimeErrors: errors }
  const checkOverflow = async (width) => {
    await page.setViewportSize({ width, height: 1000 })
    await page.waitForTimeout(600)
    const size = await page.evaluate(() => ({ viewport: innerWidth, scroll: document.documentElement.scrollWidth }))
    assert.ok(size.scroll <= size.viewport + 1, `horizontal overflow at ${width}: ${size.scroll}`)
    report.checks.push(`no page overflow at ${width}px`)
  }
  await checkOverflow(1440)
  await page.screenshot({ path: 'artifacts/cn/desktop.png', fullPage: true })
  await page.getByLabel('选择图表指标').selectOption('cpi')
  await page.getByRole('button', { name: '10年', exact: true }).click()
  await page.getByLabel('搜索指标').fill('财政')
  assert.ok(await page.locator('tbody tr').count() >= 1)
  await page.getByLabel('搜索指标').fill('')
  const csvButton = page.getByRole('button', { name: '下载完整历史CSV', exact: true })
  if (await csvButton.isEnabled()) {
    const pending = page.waitForEvent('download')
    await csvButton.click()
    const download = await pending
    await download.saveAs('artifacts/cn/history.csv')
    assert.ok((await fs.readFile('artifacts/cn/history.csv', 'utf8')).split('\n').length > 24)
    report.checks.push('real historical CSV export >24 observations')
  }
  for (const width of [768, 390, 320]) await checkOverflow(width)
  await page.setViewportSize({ width: 390, height: 844 })
  await page.screenshot({ path: 'artifacts/cn/mobile.png', fullPage: true })
  await page.getByRole('button', { name: '化债与传导', exact: true }).click()
  await page.getByText('直接增加的置换资源是10万亿元，不是12万亿元新增刺激。').waitFor()
  await checkOverflow(390)
  await page.screenshot({ path: 'artifacts/cn/transmission.png', fullPage: true })
  await page.getByRole('button', { name: '历史与情景', exact: true }).click()
  const duration = page.getByLabel('修正久期')
  await duration.focus()
  await duration.press('Home')
  for (let i = 0; i < 14; i++) await duration.press('ArrowRight')
  const shock = page.getByLabel('收益率变化')
  await shock.focus()
  await shock.press('End')
  for (let i = 0; i < 5; i++) await shock.press('ArrowLeft')
  assert.ok((await page.textContent('main')).includes('-15'))
  await checkOverflow(320)
  await page.getByRole('button', { name: '数据与方法', exact: true }).click()
  await page.getByText('数据从哪里来，什么时候才算新？').waitFor()
  await checkOverflow(390)
  await page.getByRole('button', { name: '切换深色浅色', exact: true }).click()
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.screenshot({ path: 'artifacts/cn/methodology-light.png', fullPage: true })
  assert.equal((await context.request.get(base + '/api/cn/series?id=__proto__')).status(), 400)
  assert.equal((await context.request.get(base + '/api/cn/series?id=https://example.com')).status(), 400)
  const policies = await (await context.request.get(base + '/api/cn/policies')).json()
  report.checks.push('unknown identifiers rejected; no arbitrary upstream proxy', 'five panels navigate; search, ranges, themes, scenarios work')
  report.policies = { status: policies.status, liveCount: policies.liveCount }
  await page.goto(base + '/methodology', { waitUntil: 'domcontentloaded' })
  const cnLink = page.locator('a[data-main-nav-href="/cn"]:visible').first()
  await cnLink.waitFor()
  await cnLink.click()
  await page.waitForURL('**/cn')
  assert.equal(await page.locator('a[data-main-nav-href="/cn"]').count(), 0)
  await page.goto(base + '/methodology', { waitUntil: 'domcontentloaded' })
  await page.locator('a[data-main-nav-href="/cn"]:visible').first().waitFor()
  await page.waitForTimeout(500)
  await page.keyboard.press('Control+k')
  await page.getByRole('combobox').fill('CN')
  await page.getByRole('option', { name: /CN/ }).click()
  await page.waitForURL('**/cn')
  report.checks.push('main navigation and command palette open /cn without a duplicate header')
  await fs.writeFile('artifacts/cn/browser-report.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
  await browser.close()
  assert.equal(errors.length, 0, errors.join('\n'))
})().catch(error => { console.error(error); process.exit(1) })
