const { chromium } = require('playwright')
const fs = require('node:fs/promises')
const assert = require('node:assert/strict')
;(async () => {
  const base = process.env.CN_TEST_URL || 'http://127.0.0.1:3111'
  await fs.mkdir('artifacts/cn-market', { recursive: true })
  const browser = await chromium.launch({ headless: true })
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, locale: 'zh-CN', acceptDownloads: true })
  const page = await context.newPage(), errors = [], checks = []
  page.on('pageerror', e => errors.push(e.message))
  const response = await context.request.get(base + '/api/cn/analysis')
  assert.equal(response.status(), 200)
  const analysis = await response.json()
  assert.ok(analysis.coverage.universe > 5000)
  assert.ok(analysis.coverage.exchanges.BSE > 100)
  assert.ok(analysis.findings.length >= 3)
  const getScreen = async q => { const r = await context.request.get(`${base}/api/cn/screener?snapshotId=${analysis.snapshotId}&${q}`); assert.equal(r.status(), 200); return r.json() }
  const first = await getScreen('preset=value'), second = await getScreen('preset=value&page=2')
  assert.ok(first.total > 9); assert.equal(first.items.length, 50)
  assert.equal(first.snapshotId, second.snapshotId)
  assert.equal(new Set([...first.items, ...second.items].map(i => i.row.id)).size, first.items.length + second.items.length)
  assert.ok(first.items.every(i => i.row.revenueGrowth > 0 && i.row.profitGrowth > 0 && i.row.annualRoe >= 10 && i.row.operatingCashFlow > 0 && i.row.pePercentile <= 40))
  const bj = await getScreen('preset=custom&exchange=BSE')
  assert.ok(bj.total > 100); assert.ok(bj.items.every(i => i.row.exchange === 'BSE' && i.row.identityVerified))
  const bank = await getScreen('preset=financial')
  assert.ok(bank.total > 0 && bank.items.every(i => i.row.financial && i.row.pb > 0 && i.row.pb <= 1))
  const empty = await getScreen('preset=value&roeMin=999999')
  assert.equal(empty.total, 0); assert.ok(empty.excluded.length)
  for (const q of ['pageSize=101', 'peMax=NaN', 'url=https://example.com', 'snapshotId=../../secret']) assert.equal((await context.request.get(base + '/api/cn/screener?' + q)).status(), 400)
  assert.equal((await context.request.get(base + '/api/cn/screener?snapshotId=cn-20000101-0123456789ab')).status(), analysis.mode === 'archive' ? 503 : 410)
  checks.push('real market coverage, all three presets, BSE identities, numeric gates, pinned pagination, empty reasons and input rejection')
  await page.goto(base + '/cn', { waitUntil: 'domcontentloaded' })
  await page.getByTestId('cn-screen-count').waitFor({ timeout: 45000 })
  await page.getByRole('heading', { name: '数字对应的当前判断' }).waitFor()
  await page.getByRole('heading', { name: '需求与景气', exact: true }).waitFor()
  await page.getByTestId('cn-company-detail').waitFor()
  await page.screenshot({ path: 'artifacts/cn-market/overview.png', fullPage: true })
  await page.getByRole('navigation', { name: '中国观察导航' }).getByRole('button', { name: '全市场筛选', exact: true }).click()
  await page.getByLabel('搜索全市场公司').waitFor()
  await page.getByLabel('搜索全市场公司').fill(first.items[0].row.code)
  await page.getByRole('button', { name: '应用筛选条件', exact: true }).click()
  await page.getByTestId('cn-screen-count').filter({ hasText: '1家公司' }).waitFor()
  assert.ok((await page.getByTestId('cn-company-detail').textContent()).includes(first.items[0].row.name))
  await page.getByLabel(`加入观察清单 ${first.items[0].row.code}`, { exact: true }).click()
  await page.getByLabel('我的投资假设', { exact: true }).fill('全市场验证：继续复核原始财报与一次性损益。')
  await page.getByRole('button', { name: '保存研究记录', exact: true }).click()
  await page.reload({ waitUntil: 'domcontentloaded' })
  await page.getByTestId('cn-screen-count').filter({ hasText: '1家公司' }).waitFor({ timeout: 45000 })
  assert.equal(await page.getByLabel('我的投资假设', { exact: true }).inputValue(), '全市场验证：继续复核原始财报与一次性损益。')
  await page.getByLabel(`移出观察清单 ${first.items[0].row.code}`, { exact: true }).waitFor()
  const pending = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出全部结果', exact: true }).click()
  const d = await pending; await d.saveAs('artifacts/cn-market/export.json')
  const exported = JSON.parse(await fs.readFile('artifacts/cn-market/export.json', 'utf8'))
  assert.equal(exported.snapshotId, analysis.snapshotId); assert.equal(exported.items.length, 1)
  assert.ok(exported.notebook.watchlist.includes(first.items[0].row.id))
  checks.push('first visit shows real economic conclusions and companies; search, notes, watchlist, URL reload and provenance export work')
  await page.getByRole('button', { name: '清除为自定义', exact: true }).click()
  await page.getByLabel('筛选市场').selectOption('BSE')
  await page.getByRole('button', { name: '应用筛选条件', exact: true }).click()
  await page.getByTestId('cn-screen-count').filter({ hasText: `${bj.total}家公司` }).waitFor()
  await page.getByText('调整估值与财务门槛', { exact: true }).click()
  await page.getByLabel('完整年度ROE下限（%）', { exact: true }).fill('999999')
  await page.getByRole('button', { name: '应用筛选条件', exact: true }).click()
  await page.getByRole('heading', { name: '当前条件没有匹配公司' }).waitFor()
  await page.getByRole('button', { name: '清除为自定义', exact: true }).click()
  for (const width of [1440, 768, 390, 320]) {
    await page.setViewportSize({ width, height: 1000 })
    const size = await page.evaluate(() => ({ viewport: innerWidth, scroll: document.documentElement.scrollWidth }))
    assert.ok(size.scroll <= size.viewport + 1, `overflow at ${width}: ${size.scroll}`)
    checks.push(`no page overflow at ${width}px`)
  }
  await page.screenshot({ path: 'artifacts/cn-market/mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: '切换深色浅色', exact: true }).click()
  await page.screenshot({ path: 'artifacts/cn-market/screener-light.png', fullPage: true })
  const extra = bj.items.find(i => !['sh601668', 'sh600036', 'sh600031', 'sh600900'].includes(i.row.id))
  const financialResponse = await context.request.get(base + '/api/cn/fundamentals?id=' + extra.row.id)
  assert.equal(financialResponse.status(), 200)
  const financial = await financialResponse.json()
  assert.equal(financial.id, extra.row.id)
  assert.ok(['ok', 'partial', 'unavailable'].includes(financial.status))
  checks.push('dynamic BSE company fundamentals no longer limited to four stocks; light and dark layouts render')
  assert.deepEqual(errors, [])
  const report = { testedAt: new Date().toISOString(), snapshotId: analysis.snapshotId, coverage: analysis.coverage, tradeDate: analysis.tradeDate, reportDate: analysis.reportDate, mode: analysis.mode, presets: analysis.presets, dynamicFundamentals: { id: financial.id, status: financial.status }, checks, runtimeErrors: errors }
  await fs.writeFile('artifacts/cn-market/browser-report.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
  await browser.close()
})().catch(e => { console.error(e); process.exit(1) })
